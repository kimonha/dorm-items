import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import vm from 'node:vm';
const source=await fs.readFile(new URL('../static/app.js',import.meta.url),'utf8');
const code=source.slice(source.indexOf('function selectionIntervals()'),source.indexOf('let bookingPending=false;'));
const elements={'#slots':{innerHTML:''},'#selection':{textContent:''},'#book':{disabled:false},'#booking-date':{value:'2030-01-07'}};
const buttons=Array.from({length:6},(_,i)=>({dataset:{slot:String(i)}}));
const slots=Array.from({length:6},(_,i)=>({start:`${String(9+Math.floor(i/2)).padStart(2,'0')}:${i%2?'30':'00'}`,end:`${String(9+Math.floor((i+1)/2)).padStart(2,'0')}:${(i+1)%2?'30':'00'}`,available:true,remaining:2,quantity:3,reason:''}));
const scope={$:s=>elements[s],document:{querySelectorAll:()=>buttons},slots,selected:[],bookingPending:false,currentItem:{quantity:3},empty:s=>s,toast(){}};
vm.createContext(scope);vm.runInContext(code,scope);scope.paintSlots();
assert.doesNotMatch(elements['#slots'].innerHTML,/잔여|2\/3/,'Time cards must not show remaining counts');
assert.match(elements['#slots'].innerHTML,/예약 가능/);
buttons[0].onclick();assert.equal(scope.selected.join(),'0');
buttons[0].onclick();assert.equal(scope.selected.length,0);assert.equal(elements['#book'].disabled,true);
buttons[0].onclick();buttons[1].onclick();buttons[2].onclick();
assert.equal(scope.selected.join(),'0,1,2');
buttons[1].onclick();assert.equal(scope.selected.join(),'0,2','Only the clicked interval must be deselected');
assert.equal(scope.selectionIntervals().length,2);
assert.match(elements['#selection'].textContent,/09:00–09:30 \/ 10:00–10:30/);
buttons[1].onclick();assert.equal(scope.selected.join(),'0,1,2','An individual interval can be reselected');
assert.equal(scope.selectionIntervals().length,1);
buttons[3].onclick();buttons[4].onclick();assert.equal(scope.selected.length,4,'Cannot exceed two hours in total');
buttons[0].onclick();assert.equal(scope.selected.join(),'1,2,3','Endpoint removal must preserve other selected intervals');
scope.bookingPending=true;buttons[1].onclick();assert.equal(scope.selected.join(),'1,2,3');
console.log('Slot selection: independent toggles, exact interior removal, reselection, two-hour limit, split intervals and pending guard passed.');
